# group_service.py
"""Listing 30.2 — Python: the group service layer (executable model of Listing 30.3's Kotlin and
Swift). It drives the REAL Rust core of Listing 30.1 through its UniFFI bindings — the same
interface the apps use — and supplies the three platform callbacks: the SQLCipher-backed
`MlsStore`, the `IdentityDirectory` built from verified device lists, and the identity-key
`CredentialBinder`. It owns the network side: KeyPackages, DS commits with retry, fan-out
routing, and the receive loop where MLS processing and the inbox share ONE transaction."""
import base64, json, os, re, time
import xeddsa, murmur_pb2 as pb
import murmur_groups as mg                      # generated by uniffi-bindgen from Listing 30.1
from murmur_client import b64, unb64

class SqlCipherMlsStore(mg.MlsStore):
    """mls_kv in core.db. If the caller already holds a transaction (the receive loop), the
    core's batch JOINS it, so MLS state, inbox and dedupe commit together or not at all."""
    def __init__(self, db):
        self.db = db
        db.execute("CREATE TABLE IF NOT EXISTS mls_kv (k BLOB PRIMARY KEY, v BLOB NOT NULL)")
    def load_all(self):
        return [mg.Kv(key=k, value=v) for k, v in self.db.execute("SELECT k, v FROM mls_kv")]
    def commit(self, puts, deletes):
        own = not self.db.in_transaction
        if own: self.db.execute("BEGIN IMMEDIATE")
        try:
            self.db.executemany("INSERT OR REPLACE INTO mls_kv VALUES (?,?)", [(kv.key, kv.value) for kv in puts])
            self.db.executemany("DELETE FROM mls_kv WHERE k=?", [(k,) for k in deletes])
            if own: self.db.execute("COMMIT")
        except Exception as e:
            if own: self.db.execute("ROLLBACK")
            raise mg.GroupError.Storage(str(e))

class VerifiedDirectory(mg.IdentityDirectory):
    """The AS as the core sees it: answers ONLY from device lists this device has verified
    under the account's AIK (Ch 29 §29.1). Never does network I/O (it runs inside transactions)."""
    def __init__(self, messenger): self.m = messenger
    def identity_key(self, account, device):
        r = self.m.db.execute("SELECT devices FROM contacts WHERE account=?", (account,)).fetchone()
        if not r or not r[0]: return None
        ik = json.loads(r[0]).get(device)
        return bytes.fromhex(ik) if ik else None

class IdentityBinder(mg.CredentialBinder):
    def __init__(self, messenger): self.m = messenger
    def bind(self, message): return xeddsa.sign(self.m.ik.priv, message)   # XEdDSA by the device IK

NOT_LISTED = re.compile(r"(\S+)/\S+ is not in (\S+)'s verified device list")

class GroupService:
    def __init__(self, messenger):
        self.m = messenger
        self.store = SqlCipherMlsStore(messenger.db)
        self.reopen()
        self.m.db.execute("CREATE TABLE IF NOT EXISTS group_inbox (group_id BLOB, sender TEXT, text TEXT, at REAL)")

    def reopen(self):
        """After any rollback the in-memory core may be ahead of the database: reload it."""
        self.core = mg.MurmurGroups.open(self.m.account, self.m.device_id, self.store,
                                         VerifiedDirectory(self.m), IdentityBinder(self.m))

    @property
    def name(self): return f"{self.m.account}/{self.m.device_id}"

    # ── KeyPackages (Ch 23 §23.8), kept stocked like prekeys (Ch 28 §28.5) ──
    def publish_key_packages(self, n=5):
        kps = self.core.key_packages(n, False)
        lr = self.core.key_packages(1, True)[0]
        return self.m.call("PUT", "/v1/mls/keypackages", {"key_packages": [b64(k) for k in kps], "last_resort": b64(lr)})[0]

    def _claim(self, device):
        st, js = self.m.call("GET", f"/v1/mls/keypackage/{device}")
        return unb64(js["key_package"]) if st == 200 else None

    def _devices_of(self, account):
        return {d: k for d, k in self.m.refresh_contact(account).items()}   # network, verified, OUTSIDE tx

    # ── commits through the DS, with the conflict protocol of §30.3 ──
    def _submit(self, gid, build, joiners=(), removed=(), attempts=3):
        for attempt in range(attempts):
            out = build()                                            # a fresh commit for the CURRENT epoch
            members = [n.split("/", 1)[1] for n in self.core.members(gid) if n not in removed]
            members += [j for j in joiners if j not in members]
            st, js = self.m.call("POST", "/v1/groups/commit", {"message": b64(out.commit), "members": members,
                                 "joiners": list(joiners), "welcome": b64(out.welcome) if out.welcome else None})
            if st == 202:
                return self.core.merge_pending(gid), attempt
            if st == 409 and js.get("code") == "STALE_EPOCH":
                self.core.clear_pending(gid)                         # our commit lost the race
                self.receive()                                       # process the winner first
                continue
            self.core.clear_pending(gid)
            raise RuntimeError(f"commit refused: {st} {js}")
        raise RuntimeError("commit kept losing the race")

    def create(self, admins, accounts):
        gid = self.core.create_group(admins)
        targets = {}
        for a in accounts:                                           # every device of every account,
            for d in self._devices_of(a):                            # including our own other devices
                if d != self.m.device_id: targets[d] = a
        kps = [k for k in (self._claim(d) for d in targets) if k]
        epoch, _ = self._submit(gid, lambda: self.core.add_members(gid, kps), joiners=list(targets))
        return gid, epoch

    def add_devices(self, gid, devices):
        kps = [self._claim(d) for d in devices]
        return self._submit(gid, lambda: self.core.add_members(gid, kps), joiners=list(devices))

    def remove(self, gid, names):
        return self._submit(gid, lambda: self.core.remove_members(gid, names), removed=names)

    def self_update(self, gid):
        return self._submit(gid, lambda: self.core.self_update(gid))

    def leave(self, gid):
        p = self.core.leave(gid)
        return self.m.call("POST", "/v1/groups/message", {"message": b64(p)})[0]

    def commit_proposals(self, gid, leaving):
        return self._submit(gid, lambda: self.core.commit_pending_proposals(gid), removed=leaving)

    def send(self, gid, text):
        ct = self.core.encrypt(gid, text.encode())                   # persisted before it leaves
        st, js = self.m.call("POST", "/v1/groups/message", {"message": b64(ct)})
        return st, len(ct)

    # ── receive: MLS processing + inbox + dedupe in ONE transaction, then ack ──
    def receive(self):
        st, q = self.m.call("GET", "/v1/messages")
        out, acked = [], []
        for e in q["envelopes"]:
            env = pb.Envelope.FromString(unb64(e["body"]))
            if env.type not in (pb.MLS_MESSAGE, pb.MLS_WELCOME):
                r = self.m._process(unb64(e["guid"]), unb64(e["body"]), None, [])   # 1:1 (Ch 29)
                out.append(r); acked.append(e["guid"]); continue
            for retry in range(2):
                self.m.db.execute("BEGIN IMMEDIATE")
                try:
                    if self.m.db.execute("SELECT 1 FROM processed WHERE guid=?", (unb64(e["guid"]),)).fetchone():
                        r = None
                    elif env.type == pb.MLS_WELCOME:
                        gid = self.core.join(env.content)
                        r = ("joined", gid.hex()[:8], self.core.members(gid))
                    else:
                        p = self.core.process(env.content)
                        r = self._record(p)
                    if r and r[0] == "rejected" and retry == 0 and (mm := NOT_LISTED.search(r[1])):
                        raise LookupError(mm.group(2))               # unknown device: refresh, retry once
                    self.m.db.execute("INSERT OR IGNORE INTO processed VALUES (?,?)", (unb64(e["guid"]), time.time()))
                    self.m.db.execute("COMMIT")
                    break
                except LookupError as missing:
                    self.m.db.execute("ROLLBACK"); self.reopen()
                    self.m.refresh_contact(str(missing.args[0]))     # network, outside the transaction
                except mg.GroupError as err:
                    self.m.db.execute("ROLLBACK"); self.reopen()
                    self.m.db.execute("INSERT OR IGNORE INTO processed VALUES (?,?)", (unb64(e["guid"]), time.time()))
                    r = ("undecryptable", str(err)[:70]); break
            if r: out.append(r)
            acked.append(e["guid"])
        if acked: self.m.call("POST", "/v1/messages/ack", {"guids": acked})
        return out

    def _record(self, p):
        if p.is_application():
            self.m.db.execute("INSERT INTO group_inbox VALUES (?,?,?,?)", (p.group_id, p.sender, p.plaintext.decode(), time.time()))
            return ("message", p.sender.split("/")[0], p.plaintext.decode())
        if p.is_commit_merged(): return ("commit", p.epoch, p.added, p.removed)
        if p.is_removed_from_group(): return ("removed-from-group", p.group_id.hex()[:8])
        if p.is_proposal_stored(): return ("proposal", p._from)
        return ("rejected", p.reason)

    def safety_code(self, gid):
        """The group's epoch authenticator, shown as 4 groups of 5 digits (§30.4)."""
        ea = self.core.epoch_authenticator(gid)
        return " ".join(f"{int.from_bytes(ea[i:i + 5], 'big') % 100000:05d}" for i in range(0, 20, 5))
