import android.app.Activity
import android.content.Intent
import android.net.Uri
import android.util.Base64
import androidx.activity.result.ActivityResultLauncher
import androidx.activity.result.contract.ActivityResultContracts
import androidx.appcompat.app.AppCompatActivity
import java.security.MessageDigest
import java.security.SecureRandom
import net.openid.appauth.*

// --- PKCE by hand (AppAuth does this for you; shown so the mechanism is
// visible) ---
object Pkce {
    private fun b64url(b: ByteArray) =
        Base64.encodeToString(b,
            Base64.URL_SAFE or Base64.NO_PADDING or Base64.NO_WRAP)

    // 43 chars
    fun verifier(): String = ByteArray(32).also { SecureRandom().nextBytes(
        it) }.let(::b64url)
    fun challenge(verifier: String): String =
        b64url(MessageDigest.getInstance("SHA-256").digest(verifier.toByteArray(
            Charsets.US_ASCII)))
}

class LoginActivity : AppCompatActivity() {
    private val issuer = Uri.parse("https://auth.murmur.example")
    // claimed App Link
    private val redirect = Uri.parse(
        "https://app.murmur.example/oauth/callback")
    private lateinit var authService: AuthorizationService
    private lateinit var launcher: ActivityResultLauncher<Intent>

    override fun onCreate(savedInstanceState: android.os.Bundle?) {
        super.onCreate(savedInstanceState)
        // uses a Custom Tab when available
        authService = AuthorizationService(this)
        launcher = registerForActivityResult(
            ActivityResultContracts.StartActivityForResult()) { result ->
            val data = result.data ?: return@registerForActivityResult
            val resp = AuthorizationResponse.fromIntent(data)
            val err = AuthorizationException.fromIntent(data)
            if (resp == null) { showError(err);
                return@registerForActivityResult }
            // AppAuth has already checked `state`. Check `iss` (RFC 9207) where
            // the AS sends it.
            val iss = data.data?.getQueryParameter(
                "iss") ?: resp.additionalParameters["iss"]
            if (iss != null && iss != issuer.toString()) { showError(null);
                return@registerForActivityResult }
            // Token exchange: AppAuth sends code + redirect_uri + client_id +
            // code_verifier.
            authService.performTokenRequest(
                resp.createTokenExchangeRequest()) { tokens, tokenErr ->
                if (tokens != null) TokenStore.save(this,
                    tokens) else showError(tokenErr)
            }
        }
    }

    fun signIn() {
        // Discovery: /.well-known/openid-configuration (Chapter 12) → endpoints
        // + issuer
        AuthorizationServiceConfiguration.fetchFromIssuer(issuer) { config,
            ex ->
            if (config == null) { showError(ex); return@fetchFromIssuer }
            val request = AuthorizationRequest.Builder(config, "murmur-android",
                    ResponseTypeValues.CODE, redirect)
                .setScopes("openid", "messages:send", "messages:read",
                    "contacts:read")
                // state, nonce and PKCE (S256) are generated by AppAuth
                // automatically
                .build()
            launcher.launch(authService.getAuthorizationRequestIntent(request))
        }
    }

    override fun onDestroy() { authService.dispose(); super.onDestroy() }
    private fun showError(e: Exception?) {
        /* show a retryable error; never log codes or tokens */ }
}
